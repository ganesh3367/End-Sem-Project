// Function to generate more items
const generateMoreItems = () => {
  const baseItems = [...furnitureData];
  const newItems = [];
  let id = furnitureData.length + 1;

  // Generate variations for each base item
  baseItems.forEach(baseItem => {
    for (let i = 1; i <= 4; i++) {
      newItems.push({
        id: id++,
        name: `${baseItem.name} - Style ${i}`,
        price: baseItem.price * (0.8 + Math.random() * 0.4), // Price variation
        category: baseItem.category,
        image: baseItem.image,
        description: `${baseItem.description} - Variation ${i}`
      });
    }
  });

  return [...furnitureData, ...newItems];
};

// Export the expanded data
export const expandedFurnitureData = generateMoreItems(); 